-- relationship table between book and author
CREATE TABLE BOOK_AUTHOR (
    BOOK_ID INTEGER,
    AUTHOR_ID INTEGER,
    PRIMARY KEY (BOOK_ID, AUTHOR_ID),
    CONSTRAINT fk_book
        FOREIGN KEY (BOOK_ID)
        REFERENCES BOOK(ID)
        ON DELETE CASCADE,
    CONSTRAINT fk_author
        FOREIGN KEY (AUTHOR_ID)
        REFERENCES AUTHOR(ID)
);

CREATE TABLE GENRE (
    ID INT GENERATED AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE TITLE_GENRE (
   TITLE_ID INTEGER,
   GENRE_ID INTEGER,
   PRIMARY KEY (TITLE_ID, GENRE_ID),
   CONSTRAINT fk_title
       FOREIGN KEY (TITLE_ID)
       REFERENCES TITLE(ID),
   CONSTRAINT fk_genre
       FOREIGN KEY (GENRE_ID)
       REFERENCES GENRE(ID)
);

CREATE TABLE COPY (
    ID INT GENERATED AS IDENTITY PRIMARY KEY,
    STATUS VARCHAR(20) NOT NULL CHECK (STATUS IN ('available', 'borrowed', 'reserved')),
    LOCATION VARCHAR(100) NOT NULL,
    TITLE_ID INTEGER NOT NULL,
    CONSTRAINT fk_copy_title
        FOREIGN KEY (TITLE_ID)
        REFERENCES TITLE(ID)
        ON DELETE CASCADE
);

CREATE TABLE RESERVATION (
    ID INT GENERATED AS IDENTITY PRIMARY KEY,
    DATE_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR(20) NOT NULL CHECK (STATUS IN ('canceled', 'active','completed')),
    READER_ID INTEGER NOT NULL,
    TITLE_ID INTEGER NOT NULL,
    CONSTRAINT fk_reservation_reader
        FOREIGN KEY (READER_ID)
        REFERENCES READER(ID),
    CONSTRAINT fk_reservation_title
        FOREIGN KEY (TITLE_ID)
        REFERENCES TITLE(ID)
);

CREATE TABLE LOAN(
    ID INT GENERATED AS IDENTITY PRIMARY KEY,
    BORROW_DATE TIMESTAMP NOT NULL,
    DUE_DATE TIMESTAMP NOT NULL,  -- deadline
    RETURN_DATE TIMESTAMP,        -- real date return
    STATUS VARCHAR(20) DEFAULT 'active'
       CHECK (STATUS IN ('active', 'returned', 'overdue')),
    READER_ID INTEGER NOT NULL,
    COPY_ID INTEGER,
    WORKER_ID INTEGER,
    CONSTRAINT chk_due_date CHECK (DUE_DATE > BORROW_DATE),
    CONSTRAINT fk_loan_reader
        FOREIGN KEY (READER_ID)
        REFERENCES READER(ID),
    CONSTRAINT fk_loan_copy
        FOREIGN KEY (COPY_ID)
        REFERENCES COPY(ID)
        ON DELETE SET NULL,
    CONSTRAINT fk_loan_worker
        FOREIGN KEY (WORKER_ID)
        REFERENCES WORKER(ID)
);

