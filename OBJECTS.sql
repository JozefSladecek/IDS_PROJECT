-- relationship table between book and author
CREATE TABLE BOOK_AUTHOR (
    BOOK_ID INTEGER REFERENCES BOOK(ID),
    AUTHOR_ID INTEGER REFERENCES AUTHOR(ID),
    PRIMARY KEY (BOOK_ID, AUTHOR_ID)
);


CREATE TABLE GENRE (
    ID INTEGER PRIMARY KEY DEFAULT nextval('genre_seq'),
    NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE TITLE_GENRE (
    TITLE_ID INTEGER REFERENCES TITLE(ID),
    GENRE_ID INTEGER REFERENCES GENRE(ID),
    PRIMARY KEY (TITLE_ID, GENRE_ID)
);

CREATE TABLE COPY (
    ID INTEGER PRIMARY KEY DEFAULT nextval('copy_seq'),
    STATUS VARCHAR(20) NOT NULL CHECK (STATUS IN ('available', 'borrowed', 'reserved')),
    LOCATION VARCHAR(100) NOT NULL,
    TITLE_ID INTEGER NOT NULL REFERENCES TITLE(ID)
);

CREATE TABLE RESERVATION (
    ID INTEGER PRIMARY KEY DEFAULT nextval('reservation_seq'),
    DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR(20) NOT NULL CHECK (STATUS IN ('canceled', 'active','completed')),
    READER_ID INTEGER NOT NULL REFERENCES READER(ID),
    TITLE_ID INTEGER NOT NULL REFERENCES TITLE(ID)
);

CREATE TABLE LOAN(
    ID          INTEGER PRIMARY KEY DEFAULT nextval('loan_seq'),
    BORROW_DATE TIMESTAMP    NOT NULL,
    DUE_DATE    TIMESTAMP NOT NULL,   -- deadline
    RETURN_DATE TIMESTAMP,            -- real date of return,
    READER_ID   INTEGER NOT NULL REFERENCES READER (ID),
    COPY_ID     INTEGER NOT NULL REFERENCES COPY (ID),
    WORKER_ID   INTEGER REFERENCES WORKER (ID)
);


